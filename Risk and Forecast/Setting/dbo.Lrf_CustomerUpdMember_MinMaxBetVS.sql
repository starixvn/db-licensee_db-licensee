			RETURN
		END
	END

	IF @MaxPerMatch <> @maxpermatch_old
	BEGIN
		UPDATE custInfo
		SET	maxpermatch180 = @maxpermatch
		WHERE custid = @custid
		
		IF (@@error <> 0)
		BEGIN
			SELECT @ErrMsg = @UserName + ': '+
